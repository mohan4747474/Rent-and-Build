CREATE TABLE users (
  id VARCHAR2(36 CHAR) PRIMARY KEY,
  email VARCHAR2(320 CHAR) NOT NULL UNIQUE,
  password_hash VARCHAR2(255 CHAR) NOT NULL,
  name VARCHAR2(120 CHAR) NOT NULL,
  phone VARCHAR2(32 CHAR) NOT NULL,
  role VARCHAR2(16 CHAR) DEFAULT 'customer' NOT NULL
    CHECK (role IN ('customer', 'owner', 'operator', 'admin')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  deleted_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX users_email_idx ON users(email);

CREATE TABLE equipment (
  id VARCHAR2(36 CHAR) PRIMARY KEY,
  owner_id VARCHAR2(36 CHAR) NOT NULL REFERENCES users(id),
  name VARCHAR2(255 CHAR) NOT NULL,
  category VARCHAR2(255 CHAR) NOT NULL,
  vehicle_number VARCHAR2(64 CHAR) NOT NULL UNIQUE,
  license_number VARCHAR2(64 CHAR) NOT NULL,
  rc_card_number VARCHAR2(64 CHAR) NOT NULL,
  city VARCHAR2(255 CHAR) NOT NULL,
  description CLOB NOT NULL,
  hourly_rate NUMBER(12, 2) NOT NULL,
  daily_rate NUMBER(12, 2) NOT NULL,
  working_hours NUMBER(10) DEFAULT 0 NOT NULL,
  odometer_km NUMBER(10) DEFAULT 0 NOT NULL,
  km_driven NUMBER(10) DEFAULT 0 NOT NULL,
  owner_phone VARCHAR2(32 CHAR) NOT NULL,
  operator_name VARCHAR2(255 CHAR) NOT NULL,
  operator_phone VARCHAR2(32 CHAR) NOT NULL,
  operator_experience VARCHAR2(255 CHAR) NOT NULL,
  sensors_working NUMBER(1) DEFAULT 0 NOT NULL CHECK (sensors_working IN (0, 1)),
  ecu_device_id VARCHAR2(128 CHAR) UNIQUE,
  available NUMBER(1) DEFAULT 1 NOT NULL CHECK (available IN (0, 1)),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  deleted_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE bookings (
  id VARCHAR2(36 CHAR) PRIMARY KEY,
  customer_id VARCHAR2(36 CHAR) NOT NULL REFERENCES users(id),
  equipment_id VARCHAR2(36 CHAR) NOT NULL REFERENCES equipment(id),
  start_at TIMESTAMP WITH TIME ZONE NOT NULL,
  end_at TIMESTAMP WITH TIME ZONE NOT NULL,
  site_address CLOB NOT NULL,
  amount_paise NUMBER(10) NOT NULL,
  status VARCHAR2(24 CHAR) DEFAULT 'requested' NOT NULL
    CHECK (status IN ('requested', 'payment_pending', 'confirmed', 'in_transit', 'on_site', 'completed', 'cancelled')),
  cancellation_fee_paise NUMBER(10),
  refund_amount_paise NUMBER(10),
  cancelled_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  deleted_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE operators (
  id VARCHAR2(36 CHAR) PRIMARY KEY,
  user_id VARCHAR2(36 CHAR) NOT NULL UNIQUE REFERENCES users(id),
  owner_id VARCHAR2(36 CHAR) NOT NULL REFERENCES users(id),
  license_number VARCHAR2(64 CHAR) NOT NULL UNIQUE,
  active NUMBER(1) DEFAULT 1 NOT NULL CHECK (active IN (0, 1)),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  deleted_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE booking_work_sessions (
  id VARCHAR2(36 CHAR) PRIMARY KEY,
  booking_id VARCHAR2(36 CHAR) NOT NULL REFERENCES bookings(id),
  operator_id VARCHAR2(36 CHAR) NOT NULL REFERENCES operators(id),
  started_at TIMESTAMP WITH TIME ZONE NOT NULL,
  ended_at TIMESTAMP WITH TIME ZONE,
  start_odometer_km NUMBER(10) NOT NULL,
  end_odometer_km NUMBER(10),
  notes CLOB,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  deleted_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE operator_history (
  id VARCHAR2(36 CHAR) PRIMARY KEY,
  operator_id VARCHAR2(36 CHAR) NOT NULL REFERENCES operators(id),
  booking_id VARCHAR2(36 CHAR) REFERENCES bookings(id),
  action VARCHAR2(255 CHAR) NOT NULL,
  occurred_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE reviews (
  id VARCHAR2(36 CHAR) PRIMARY KEY,
  customer_id VARCHAR2(36 CHAR) NOT NULL REFERENCES users(id),
  equipment_id VARCHAR2(36 CHAR) NOT NULL REFERENCES equipment(id),
  booking_id VARCHAR2(36 CHAR) NOT NULL UNIQUE REFERENCES bookings(id),
  rating NUMBER(3) NOT NULL,
  comment CLOB NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  deleted_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE favorites (
  customer_id VARCHAR2(36 CHAR) NOT NULL REFERENCES users(id),
  equipment_id VARCHAR2(36 CHAR) NOT NULL REFERENCES equipment(id),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT favorites_pk PRIMARY KEY (customer_id, equipment_id)
);

CREATE TABLE vehicle_engine_sessions (
  id VARCHAR2(36 CHAR) PRIMARY KEY,
  equipment_id VARCHAR2(36 CHAR) NOT NULL REFERENCES equipment(id),
  started_at TIMESTAMP WITH TIME ZONE NOT NULL,
  ended_at TIMESTAMP WITH TIME ZONE,
  start_odometer_km NUMBER(10) NOT NULL,
  end_odometer_km NUMBER(10),
  start_engine_hours NUMBER(10, 2) NOT NULL,
  end_engine_hours NUMBER(10, 2)
);

CREATE TABLE payment_transactions (
  id VARCHAR2(36 CHAR) PRIMARY KEY,
  booking_id VARCHAR2(36 CHAR) NOT NULL REFERENCES bookings(id),
  provider VARCHAR2(32 CHAR) DEFAULT 'razorpay' NOT NULL,
  order_id VARCHAR2(128 CHAR) NOT NULL UNIQUE,
  payment_id VARCHAR2(128 CHAR) UNIQUE,
  amount_paise NUMBER(10) NOT NULL,
  method VARCHAR2(64 CHAR),
  status VARCHAR2(16 CHAR) DEFAULT 'created' NOT NULL
    CHECK (status IN ('created', 'authorized', 'captured', 'failed', 'refunded')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  deleted_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE vehicle_telemetry_current (
  equipment_id VARCHAR2(36 CHAR) PRIMARY KEY REFERENCES equipment(id),
  latitude NUMBER(10, 7) NOT NULL,
  longitude NUMBER(10, 7) NOT NULL,
  speed_kph NUMBER(8, 2) NOT NULL,
  fuel_percent NUMBER(5, 2) NOT NULL,
  engine_on NUMBER(1) NOT NULL CHECK (engine_on IN (0, 1)),
  odometer_km NUMBER(10) NOT NULL,
  engine_hours NUMBER(10, 2) NOT NULL,
  ecu_data CLOB NOT NULL CHECK (ecu_data IS JSON),
  recorded_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE vehicle_telemetry_history (
