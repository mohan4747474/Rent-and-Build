  latitude NUMBER(10, 7) NOT NULL,
  longitude NUMBER(10, 7) NOT NULL,
  speed_kph NUMBER(8, 2) NOT NULL,
  fuel_percent NUMBER(5, 2) NOT NULL,
  engine_on NUMBER(1) NOT NULL CHECK (engine_on IN (0, 1)),
  odometer_km NUMBER(10) NOT NULL,
  engine_hours NUMBER(10, 2) NOT NULL,
  ecu_data CLOB NOT NULL CHECK (ecu_data IS JSON),
  recorded_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE notifications (
  id VARCHAR2(36 CHAR) PRIMARY KEY,
  user_id VARCHAR2(36 CHAR) NOT NULL REFERENCES users(id),
  type VARCHAR2(128 CHAR) NOT NULL,
  title VARCHAR2(255 CHAR) NOT NULL,
  body CLOB NOT NULL,
  read_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  deleted_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE audit_logs (
  id VARCHAR2(36 CHAR) PRIMARY KEY,
  actor_id VARCHAR2(36 CHAR) REFERENCES users(id),
  action VARCHAR2(255 CHAR) NOT NULL,
  entity VARCHAR2(255 CHAR) NOT NULL,
  entity_id VARCHAR2(36 CHAR),
  metadata CLOB CHECK (metadata IS JSON),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE BATCH_JOB_INSTANCE (
  JOB_INSTANCE_ID NUMBER(19) NOT NULL PRIMARY KEY,
  VERSION NUMBER(19),
  JOB_NAME VARCHAR2(100 CHAR) NOT NULL,
  JOB_KEY VARCHAR2(32 CHAR) NOT NULL,
  CONSTRAINT JOB_INST_UN UNIQUE (JOB_NAME, JOB_KEY)
);

CREATE TABLE BATCH_JOB_EXECUTION (
  JOB_EXECUTION_ID NUMBER(19) NOT NULL PRIMARY KEY,
  VERSION NUMBER(19),
  JOB_INSTANCE_ID NUMBER(19) NOT NULL REFERENCES BATCH_JOB_INSTANCE(JOB_INSTANCE_ID),
  CREATE_TIME TIMESTAMP(6) NOT NULL,
  START_TIME TIMESTAMP(6),
  END_TIME TIMESTAMP(6),
  STATUS VARCHAR2(10 CHAR),
  EXIT_CODE VARCHAR2(2500 CHAR),
  EXIT_MESSAGE VARCHAR2(2500 CHAR),
  LAST_UPDATED TIMESTAMP(6)
);

CREATE TABLE BATCH_JOB_EXECUTION_PARAMS (
  JOB_EXECUTION_ID NUMBER(19) NOT NULL REFERENCES BATCH_JOB_EXECUTION(JOB_EXECUTION_ID),
  PARAMETER_NAME VARCHAR2(100 CHAR) NOT NULL,
  PARAMETER_TYPE VARCHAR2(100 CHAR) NOT NULL,
  PARAMETER_VALUE VARCHAR2(2500 CHAR),
  IDENTIFYING CHAR(1 CHAR) NOT NULL
);

CREATE TABLE BATCH_STEP_EXECUTION (
  STEP_EXECUTION_ID NUMBER(19) NOT NULL PRIMARY KEY,
  VERSION NUMBER(19) NOT NULL,
  STEP_NAME VARCHAR2(100 CHAR) NOT NULL,
  JOB_EXECUTION_ID NUMBER(19) NOT NULL REFERENCES BATCH_JOB_EXECUTION(JOB_EXECUTION_ID),
  CREATE_TIME TIMESTAMP(6) NOT NULL,
  START_TIME TIMESTAMP(6),
  END_TIME TIMESTAMP(6),
  STATUS VARCHAR2(10 CHAR),
  COMMIT_COUNT NUMBER(19),
  READ_COUNT NUMBER(19),
  FILTER_COUNT NUMBER(19),
  WRITE_COUNT NUMBER(19),
  READ_SKIP_COUNT NUMBER(19),
  WRITE_SKIP_COUNT NUMBER(19),
  PROCESS_SKIP_COUNT NUMBER(19),
  ROLLBACK_COUNT NUMBER(19),
  EXIT_CODE VARCHAR2(2500 CHAR),
  EXIT_MESSAGE VARCHAR2(2500 CHAR),
  LAST_UPDATED TIMESTAMP(6)
);

CREATE TABLE BATCH_STEP_EXECUTION_CONTEXT (
  STEP_EXECUTION_ID NUMBER(19) NOT NULL PRIMARY KEY REFERENCES BATCH_STEP_EXECUTION(STEP_EXECUTION_ID),
  SHORT_CONTEXT VARCHAR2(2500 CHAR) NOT NULL,
  SERIALIZED_CONTEXT CLOB
);

CREATE TABLE BATCH_JOB_EXECUTION_CONTEXT (
  JOB_EXECUTION_ID NUMBER(19) NOT NULL PRIMARY KEY REFERENCES BATCH_JOB_EXECUTION(JOB_EXECUTION_ID),
  SHORT_CONTEXT VARCHAR2(2500 CHAR) NOT NULL,
  SERIALIZED_CONTEXT CLOB
);

CREATE SEQUENCE BATCH_STEP_EXECUTION_SEQ START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE SEQUENCE BATCH_JOB_EXECUTION_SEQ START WITH 1 INCREMENT BY 1 NOCYCLE;
